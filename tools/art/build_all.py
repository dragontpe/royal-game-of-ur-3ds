#!/usr/bin/env python3
"""Build every 2D asset: fonts (gfx/fonts + source/glyphs.[ch]), sprites
(gfx/art + gfx/art.t3s, packed by tex3ds during `make`) and the 3D decal
texture (romfs/tex/decals.t3x).

    python3 tools/art/build_all.py          # theme A (lapis)
    UR_THEME=B python3 tools/art/build_all.py
"""
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import ROOT, THEME
import fonts
import ui_art
import keyart  # noqa: F401  (writes gfx/keyart on import)

fonts.build()

# theme colours for the C side (source/theme.h)
from common import T, SHELL, SHELL_HI, SHELL_LO, INK, GOLD, CARNELIAN, LAPIS
lines = ['/* Generated by tools/art/build_all.py from tools/art/common.py. Do not edit. */',
         '#ifndef UR_THEME_H', '#define UR_THEME_H', '#include <citro2d.h>', '#define UR_THEME_%s 1' % THEME]
for k, v in sorted(T.items()):
    lines.append('#define COL_%s C2D_Color32(%d, %d, %d, 255)' % (k.upper(), v[0], v[1], v[2]))
for k, v in (('SHELL', SHELL), ('SHELL_HI', SHELL_HI), ('SHELL_LO', SHELL_LO), ('INK', INK), ('GOLD', GOLD),
             ('CARNELIAN', CARNELIAN), ('LAPIS', LAPIS)):
    lines.append('#define COL_P_%s C2D_Color32(%d, %d, %d, 255)' % (k, v[0], v[1], v[2]))
lines += ['#endif', '']
open(os.path.join(ROOT, 'source', 'theme.h'), 'w').write('\n'.join(lines))
ui_art.build()
subprocess.check_call([sys.executable, os.path.join(ROOT, 'tools', 'art', 'decals.py')])
os.makedirs(os.path.join(ROOT, 'romfs', 'tex'), exist_ok=True)
subprocess.check_call(['/opt/devkitpro/tools/bin/tex3ds', '-f', 'rgba8888', '-z', 'none', '-o',
                       os.path.join(ROOT, 'romfs', 'tex', 'decals.t3x'), os.path.join(ROOT, 'gfx', 'decals.png')])
print('art ok, theme', THEME)
