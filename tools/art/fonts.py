"""Ur text: glyph sheets rasterised by FreeType at their real pixel size,
ported from Gammon-X. citro2d draws bcfnt fonts at one fixed glyph height
(blurry at every other size), so text uses our own renderer. Colours are
baked in because image tinting doesn't render in Azahar.
"""
import os
from PIL import Image, ImageDraw
from common import *

FULL = "".join(chr(c) for c in range(32, 127)) + "\u00b7\u00a9"
DIGITS = "0123456789/"
SHEET_W = 512

# name: (face, weight, px, colour, charset). Order = enum order in glyphs.h.
STYLES = [
    ("head", "poppins", "SemiBold", 15, T['text'], FULL),
    ("body", "poppins", "Medium", 11, T['soft'], FULL),
    ("text", "poppins", "Medium", 12, T['text'], FULL),
    ("quote", "poppins", "MediumItalic", 12, T['quote'], FULL),
    ("tile", "poppins", "SemiBold", 14, T['tile_text'], FULL),
    ("tile_soft", "poppins", "Medium", 11, T['tile_soft'], FULL),
    ("num", "poppins", "Bold", 13, T['box_text'], FULL),
    ("big", "poppins", "Bold", 22, T['box_text'], FULL),
    ("btn", "poppins", "SemiBold", 18, T['btn_text'], FULL),
    ("title", "cinzel", "Bold", 20, T['accent'], FULL),
    ("huge", "cinzel", "Bold", 30, T['text'], FULL),
    ("top", "poppins", "SemiBold", 16, SHELL_HI, FULL),
    ("top_soft", "poppins", "Medium", 12, SHELL, FULL),
]


def build_style(name, face, weight, px, color, chars):
    f = font(face, weight, px)
    asc, desc = f.getmetrics()
    line = asc + desc
    cap = f.getbbox("H")
    mid = (cap[1] + cap[3]) / 2.0
    cells, glyphs = [], []
    x, y, rows = 1, 0, 1
    for ch in chars:
        bb = f.getbbox(ch)
        w = max(1, bb[2] - bb[0]) if ch != " " else 1
        if x + w + 1 > SHEET_W:
            x, y = 1, y + line + 1
            rows += 1
        cells.append((ch, x, y, w, bb[0]))
        x += w + 1
    sheet = Image.new("RGBA", (SHEET_W, rows * (line + 1)), (0, 0, 0, 0))
    for ch, gx, gy, w, x0 in cells:
        if ch == " ":
            continue
        g = Image.new("L", (w + 4, line), 0)
        ImageDraw.Draw(g).text((-x0, 0), ch, font=f, fill=255)
        g = g.crop((0, 0, w, line))
        solid = Image.new("RGBA", (w, line), tuple(color) + (255,))
        solid.putalpha(g)
        sheet.alpha_composite(solid, (gx, gy))
    for ch, gx, gy, w, x0 in cells:
        glyphs.append({"ch": ch, "x": gx, "y": gy, "w": w, "off": x0, "adv": f.getlength(ch)})
    kern = []
    for a in chars:
        for b in chars:
            k = f.getlength(a + b) - f.getlength(a) - f.getlength(b)
            if abs(k) >= 0.25:
                kern.append((a, b, k))
    # tex3ds wants power-of-two-friendly heights; pad to a multiple of 8
    h = (sheet.height + 7) // 8 * 8
    if h != sheet.height:
        pad = Image.new("RGBA", (SHEET_W, h), (0, 0, 0, 0))
        pad.paste(sheet, (0, 0))
        sheet = pad
    return sheet, {"name": name, "line": line, "mid": mid, "glyphs": glyphs, "kern": kern,
                   "sheet_w": sheet.width, "sheet_h": sheet.height}


def c_char(ch):
    if ch == "'":
        return "'\\''"
    if ch == "\\":
        return "'\\\\'"
    return "'%s'" % ch if ord(ch) < 127 else "0x%02X" % ord(ch)


def build(root=ROOT):
    metas = []
    folder = os.path.join(root, "gfx", "fonts")
    os.makedirs(folder, exist_ok=True)
    for name, face, weight, px, color, chars in STYLES:
        sheet, meta = build_style(name, face, weight, px, color, chars)
        sheet.save(os.path.join(folder, name + ".png"))
        with open(os.path.join(root, "gfx", "font_%s.t3s" % name), "w") as f:
            f.write("-f rgba8888 -z auto\nfonts/%s.png\n" % name)
        metas.append(meta)

    h = ["/* Generated by tools/art/fonts.py. Do not edit. */",
         "#ifndef GLYPHS_H", "#define GLYPHS_H", "", "typedef enum {"]
    for m in metas:
        h.append("\tTS_%s," % m["name"].upper())
    h += ["\tTS_COUNT", "} text_style;", "",
          "typedef struct { unsigned char ch; short x, y, w, off; float adv; } glyph_t;",
          "typedef struct { unsigned char a, b; float k; } kern_t;",
          "typedef struct {",
          "\tconst char *path;  /* romfs t3x holding the glyph sheet */",
          "\tint sheet_w, sheet_h, line;",
          "\tfloat mid;         /* line top to the middle of a capital */",
          "\tconst glyph_t *glyphs;",
          "\tint nglyphs;",
          "\tconst kern_t *kern;",
          "\tint nkern;",
          "} font_t;", "",
          "extern const font_t text_fonts[TS_COUNT];", "", "#endif"]
    open(os.path.join(root, "source", "glyphs.h"), "w").write("\n".join(h) + "\n")

    c = ["/* Generated by tools/art/fonts.py. Do not edit. */", '#include "glyphs.h"', ""]
    for m in metas:
        c.append("static const glyph_t g_%s[] = {" % m["name"])
        for g in m["glyphs"]:
            c.append("\t{ %s, %d, %d, %d, %d, %.3ff }," % (c_char(g["ch"]), g["x"], g["y"], g["w"], g["off"], g["adv"]))
        c.append("};")
        c.append("static const kern_t k_%s[] = {" % m["name"])
        for a, b, k in m["kern"]:
            c.append("\t{ %s, %s, %.3ff }," % (c_char(a), c_char(b), k))
        if not m["kern"]:
            c.append("\t{ 0, 0, 0 },")
        c.append("};")
    c.append("")
    c.append("const font_t text_fonts[TS_COUNT] = {")
    for m in metas:
        c.append('\t{ "romfs:/gfx/font_%s.t3x", %d, %d, %d, %.2ff, g_%s, %d, k_%s, %d },' % (
            m["name"], m["sheet_w"], m["sheet_h"], m["line"], m["mid"], m["name"], len(m["glyphs"]),
            m["name"], len(m["kern"])))
    c.append("};")
    open(os.path.join(root, "source", "glyphs.c"), "w").write("\n".join(c) + "\n")


if __name__ == "__main__":
    build()
    print("fonts ok")
